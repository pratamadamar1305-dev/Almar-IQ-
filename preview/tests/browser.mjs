import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1050}});
page.setDefaultTimeout(10000);
import { mkdirSync } from 'node:fs';
mkdirSync('test-results',{recursive:true});
const errors=[]; page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://localhost:3001',{waitUntil:'networkidle'});
assert.match(await page.title(),/JedaSholat/);
await page.getByRole('button',{name:'Jadwal sholat',exact:true}).click();
await page.getByRole('button',{name:'45',exact:true}).first().click();
await page.getByRole('button',{name:'Tegas',exact:true}).first().click();
await page.getByRole('button',{name:'Aplikasi pilihan'}).click();
await page.getByPlaceholder('Cari aplikasi…').fill('TikTok');
assert.equal(await page.locator('.app-card').count(),1);
await page.getByPlaceholder('Cari aplikasi…').fill('');
await page.getByRole('button',{name:'Pengaturan',exact:true}).click();
await page.getByRole('button',{name:'Pengingat',exact:true}).click();
await page.getByRole('button',{name:'TikTok Dipilih'}).click();
await page.locator('.block-screen').waitFor({state:'visible'});
assert.equal(await page.locator('.block-screen').count(),1);
await page.getByRole('button',{name:'Tunda 5 menit · satu kali'}).click();
await page.locator('.block-screen').waitFor({state:'detached'});
assert.equal(await page.locator('.block-screen').count(),0);
await page.getByRole('button',{name:'Ulangi 30 detik · Tegas'}).click();
await page.getByRole('button',{name:'TikTok Dipilih'}).click();
await page.locator('.block-screen').waitFor({state:'visible'});
assert.equal(await page.getByRole('button',{name:'Tunda 5 menit · satu kali'}).count(),0);
await page.getByRole('button',{name:'Kembali ke simulasi'}).click();
await page.getByRole('button',{name:'Akhiri simulasi'}).click();
await page.locator('.modal-backdrop').waitFor({state:'detached'});
await page.getByRole('button',{name:'Beranda',exact:true}).click();
await page.screenshot({path:'test-results/jeda-desktop.png',fullPage:true,timeout:30000});
await page.setViewportSize({width:390,height:844});
await page.waitForTimeout(350);
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await page.screenshot({path:'test-results/jeda-mobile.png',fullPage:true,timeout:30000});
assert.deepEqual(errors,[]);
console.log('Browser checks passed: navigation, rules, search, simulation, snooze, strict mode, mobile overflow, no runtime errors.');
await browser.close();

